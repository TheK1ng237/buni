#!/usr/bin/env node
// scripts/auto-discovery.mjs
// Auto-discovery script for @buni packages
// Run this to automatically detect new components/icons/patterns and update exports

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(__dirname, '..');
const packagesRoot = path.join(pkgRoot, 'packages');

console.log('🔍 Auto-discovery for Buni packages...\n');

// ============================================================================
// 1. Discover UI Components
// ============================================================================
function discoverUIComponents() {
  const componentsDir = path.join(packagesRoot, 'ui/src/components');
  if (!fs.existsSync(componentsDir)) return [];

  const files = fs.readdirSync(componentsDir)
    .filter(f => f.endsWith('.tsx') && !f.includes('.test.') && !f.includes('.stories.'));

  const components = files.map(f => {
    const name = f.replace('.tsx', '');
    const content = fs.readFileSync(path.join(componentsDir, f), 'utf-8');

    // Extract exports
    const exports = extractExports(content);

    return {
      name,
      file: f,
      exports,
      isClient: content.includes("'use client'") || content.includes('"use client"'),
      hasDefaultExport: content.includes('export default'),
    };
  });

  return components;
}

function extractExports(content) {
  const exports = [];

  // Named exports
  const namedMatches = content.match(/export\s*{([^}]+)}/g);
  if (namedMatches) {
    for (const match of namedMatches) {
      const inner = match.match(/{([^}]+)}/);
      if (inner) {
        exports.push(...inner[1].split(',').map(s => s.trim()).filter(Boolean));
      }
    }
  }

  // Direct exports
  const directMatches = content.match(/^export\s+(const|function|class|interface|type)\s+(\w+)/gm);
  if (directMatches) {
    for (const match of directMatches) {
      const parts = match.trim().split(/\s+/);
      if (parts.length >= 3) exports.push(parts[2]);
    }
  }

  // Re-exports
  const reExportMatches = content.match(/export\s*{([^}]+)}\s*from/g);
  if (reExportMatches) {
    for (const match of reExportMatches) {
      const inner = match.match(/{([^}]+)}/);
      if (inner) {
        exports.push(...inner[1].split(',').map(s => s.trim()).filter(Boolean));
      }
    }
  }

  return [...new Set(exports)];
}

// ============================================================================
// 2. Discover Icons
// ============================================================================
function discoverIcons() {
  const iconsDir = path.join(packagesRoot, 'icons/src/icons');
  if (!fs.existsSync(iconsDir)) return [];

  const files = fs.readdirSync(iconsDir).filter(f => f.endsWith('.tsx'));
  return files.map(f => ({
    name: f.replace('.tsx', ''),
    file: f,
  }));
}

// ============================================================================
// 3. Discover Patterns (from backend sync)
// ============================================================================
function discoverPatterns() {
  const catalogPath = path.join(packagesRoot, 'patterns/src/catalog.ts');
  if (!fs.existsSync(catalogPath)) return [];

  // This is generated by sync:backend, just verify it exists
  return [{ catalog: 'catalog.ts', exists: true }];
}

// ============================================================================
// 4. Discover Tokens
// ============================================================================
function discoverTokens() {
  const tokensPath = path.join(packagesRoot, 'tokens/src/index.ts');
  if (!fs.existsSync(tokensPath)) return { exports: [], file: null };

  const content = fs.readFileSync(tokensPath, 'utf-8');
  const exports = extractExports(content);

  return { exports, file: 'index.ts' };
}

// ============================================================================
// 5. Generate Discovery Report
// ============================================================================
function generateReport() {
  const uiComponents = discoverUIComponents();
  const icons = discoverIcons();
  const patterns = discoverPatterns();
  const tokens = discoverTokens();

  console.log('📦 UI Components:', uiComponents.length);
  uiComponents.forEach(c => console.log(`  - ${c.name} (${c.exports.length} exports)`));

  console.log('\n🎨 Icons:', icons.length);
  icons.forEach(i => console.log(`  - ${i.name}`));

  console.log('\n🎭 Patterns:', patterns.length);
  console.log('\n🎨 Tokens:', tokens.exports.length, 'exports');

  // Write JSON report
  const report = {
    timestamp: new Date().toISOString(),
    ui: {
      count: uiComponents.length,
      components: uiComponents.map(c => ({
        name: c.name,
        exports: c.exports,
        isClient: c.isClient,
        hasDefaultExport: c.hasDefaultExport,
      })),
    },
    icons: {
      count: icons.length,
      icons: icons.map(i => i.name),
    },
    patterns: {
      count: patterns.length,
    },
    tokens: {
      count: tokens.exports.length,
      exports: tokens.exports,
    },
  };

  const reportPath = path.join(packagesRoot, 'discovery-report.json');
  fs.writeFileSync(reportPath, JSON.stringify(report, null, 2));
  console.log(`\n📄 Report saved to: ${reportPath}`);

  return report;
}

